'use strict';
const test=require('node:test'),assert=require('node:assert/strict');
const {readFileSync}=require('node:fs'),{join}=require('node:path');
const src=file=>readFileSync(join(__dirname,'..',file),'utf8');
test('5.1.12 uses a unique artifact and does not silently publish a tag build',()=>{
 const flow=src('.github/workflows/grena-desktop-from-kit.yml');
 assert.match(flow,/Set official 5\.1\.12 version on main/);
 assert.match(flow,/GRENA-LIVE-Installer-Windows-v5\.1\.12/);
 assert.match(flow,/electron-builder --win nsis --x64 --publish never/);
 assert.doesNotMatch(flow,/electron-builder --win nsis --x64 --publish always/);
 assert.match(flow,/verify-upgrade-5111-to-5112\.ps1/);
 assert.match(flow,/Language\.Parser\]::ParseFile/);
 assert.match(src('desktop-build/verify-upgrade-5111-to-5112.ps1'),/OK \$\{stage\}: perfil/);
});
test('upgrade gate installs 5.1.11 and 5.1.12 in same location and preserves hashed app data',()=>{
 const flow=src('.github/workflows/grena-desktop-from-kit.yml');
 const script=src('desktop-build/verify-upgrade-5111-to-5112.ps1');
 assert.match(script,/\$oldVersion='5\.1\.11'/);
 assert.match(script,/\$newVersion='5\.1\.12'/);
 assert.match(script,/Install-Silent \$oldSetup \$oldVersion/);
 assert.match(script,/Install-Silent \(@\(\$latest\)\[0\]\.FullName\) \$newVersion/);
 assert.match(script,/\$userdata=Join-Path \$env:APPDATA 'GREÑA LIVE PRO'/);
 assert.match(script,/Get-FileHash -Algorithm SHA256/);
 assert.match(script,/Assert-ProfilePreserved '5\.1\.11'/);
 assert.match(script,/Assert-ProfilePreserved '5\.1\.12'/);
 assert.match(script,/resources\\app\\node_modules/);
 assert.ok(flow.indexOf('Smoke test compiled Windows backend')<flow.indexOf('Verify installed upgrade'));
 assert.ok(flow.indexOf('Verify installed upgrade')<flow.indexOf('Upload the Windows installer'));
});
test('release 5.1.12 requires successful build at current commit and owner still approves rollout',()=>{
 const flow=src('.github/workflows/grena-release-v5112.yml');
 const up=src('desktop-build/fix_official_updates.py');
 const worker=src('cloudflare/licenses/src/updates.mjs');
 assert.match(flow,/VERSION: '5\.1\.12'/);
 assert.match(flow,/git rev-parse HEAD/);
 assert.match(flow,/\$TESTED_SHA/);
 assert.match(flow,/gh run download/);
 assert.match(flow,/sha512/);
 assert.match(flow,/gh release create/);
 assert.match(up,/tag\[1:\] if tag else '5\.1\.12'/);
 assert.match(up,/const releaseBase='https:\/\/grena-live-licenses/);
 assert.match(up,/autoUpdater\.autoDownload=false/);
 assert.match(up,/autoUpdater\.checkForUpdates\(\)/);
 assert.match(up,/lastOffered=''/);
 assert.match(worker,/api\/license-admin\/updates\/publish/);
 assert.match(worker,/api\/updates\/latest\.yml/);
 assert.match(worker,/published_version=draft_version/);
});
